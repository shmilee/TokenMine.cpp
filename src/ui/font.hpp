// Phase 15: the CPU side of the pixel font.
// Phase 35: 8x8 -> 16x16 glyphs (higher-resolution atlas, see
// tools/generate_font.py), and text scale became a DOUBLE so the
// inventory panel can scale its text proportionally when it fits the
// window (fractional glyph sizes, e.g. 0.638).
// PRE-1: the input is UTF-8 — text is decoded to codepoints (a pure
// function, see utf8NextCodepoint), and the CJK glyph set takes the
// atlas rows 0..3 (the ASCII control codes 0..31 never render, so those
// cells were dead transparent space). Reusing the dead cells keeps the
// atlas 256x512 and every ASCII glyph UV bit-identical.
//
// assets/textures/font.png (generated by tools/generate_font.py) is a
// 256x512 atlas of 32px cells: rows 4..15 hold ASCII codes 32..126
// indexed by cell (c % 8, c / 8); rows 0..3 hold the static CJK set
// (kCjkGlyphs, codepoint-sorted; the i-th entry is cell (i % 8, i / 8)).
// Each 16x16 glyph sits at an 8px offset inside its cell. Unknown /
// malformed codepoints render as the '?' glyph.
//
// UV convention (shared with the rest of the codebase — textures upload
// without flipping, so v = 0 is the image's TOP row): a glyph's v0 is its
// top edge (smaller v), v1 its bottom edge (larger v).
#pragma once

#include <cstddef>
#include <cstdint>
#include <optional>
#include <string>
#include <vector>

#include "core/math/vec2.hpp"
#include "core/math/vec3.hpp"
#include "renderer/mesh.hpp"

namespace mc {

inline constexpr int kFontAtlasWidth = 256;
inline constexpr int kFontAtlasHeight = 512;
inline constexpr int kFontCell = 32;
inline constexpr int kGlyphSize = 16;
inline constexpr int kGlyphOffset = (kFontCell - kGlyphSize) / 2; // 8

// PRE-1: the CJK glyph set (static, codepoint-sorted). The original 32
// entries occupy the dead ASCII control cells 0..31 (atlas rows 0..3 —
// ASCII codes 0..31 never render), so the i-th entry of the PRE-1 table
// is cell (i % 8, i / 8). Set = the localized UI strings' 19 characters
// (你死了按重生熔炉工作台背包合成需要关闭 — PRE-1's table carried only
// 18, omitting 作) + the 10 Chinese punctuation (，。！？：；“”（）) + a
// 4-character reserve (物品方块); pinned in tests/test_font.cpp.
// CRAFT-4 (fixing the PRE-1 omission): the crafting-table title "工作台"
// rendered "工?台" because 作 was missing. It takes the dead ASCII-DEL
// cell 127 (col 7, row 15; DEL never renders), the only free cell in the
// used rows — the atlas stays 256x512 and every PRE-1 UV (rows 0..3 +
// the ASCII rows 4..15) is bit-identical.
struct CjkGlyph {
    uint32_t cp;
    int cell; // atlas cell index (col + row * 8)
};
inline constexpr CjkGlyph kCjkGlyphs[33] = {
    {0x201C, 0}, {0x201D, 1}, {0x3002, 2}, {0x4E86, 3}, {0x4F5C, 127},
    {0x4F60, 4}, {0x5173, 5}, {0x5305, 6}, {0x53F0, 7}, {0x5408, 8},
    {0x54C1, 9}, {0x5757, 10}, {0x5DE5, 11}, {0x6210, 12}, {0x6309, 13},
    {0x65B9, 14}, {0x6B7B, 15}, {0x7089, 16}, {0x7194, 17}, {0x7269, 18},
    {0x751F, 19}, {0x80CC, 20}, {0x8981, 21}, {0x91CD, 22}, {0x95ED, 23},
    {0x9700, 24}, {0xFF01, 25}, {0xFF08, 26}, {0xFF09, 27}, {0xFF0C, 28},
    {0xFF1A, 29}, {0xFF1B, 30}, {0xFF1F, 31}};

struct GlyphUv {
    float u0 = 0.0f, v0 = 0.0f, u1 = 0.0f, v1 = 0.0f; // v0 = glyph top
};

// PRE-1: decodes the next UTF-8 codepoint of `text` starting at `pos`.
// On success returns the codepoint and advances `pos` past the whole
// sequence (1..4 bytes). On malformed input (stray continuation byte,
// truncated / overlong encoding, UTF-8 surrogate, codepoint above
// U+10FFFF) returns nullopt and advances `pos` by ONE byte, so each
// malformed byte renders as its own '?'.
std::optional<uint32_t> utf8NextCodepoint(const std::string& text,
                                          std::size_t& pos);

// The 16x16 glyph rect for a decoded codepoint: ASCII 32..126 keeps the
// original cell (cp % 8, cp / 8) — bit-identical to the pre-PRE-1
// mapping; a codepoint in kCjkGlyphs takes its set position (the i-th
// sorted entry is cell (i % 8, i / 8)); everything else maps to '?'.
// (A char argument converts to its unsigned value, so a raw byte 0x80
// renders '?' exactly as before.)
GlyphUv glyphUv(uint32_t cp);

// On-screen advance width of the whole string at `scale` (> 0; values
// <= 0 clamp to 1.0): each decoded codepoint occupies kGlyphSize*scale
// plus scale pixels of spacing (CJK codepoints use the SAME 16px
// monospace advance as ASCII — the PRE-1 width discipline). Fractional
// scales downscale the glyphs.
double textWidth(const std::string& text, double scale = 1.0);

// CRAFT-4: shrink `name` (trailing codepoints) so that `name + suffix`
// fits `availPx` at `scale` — the suffix (the " xN" output count) is
// always kept, the name is truncated last-resort so a long item id never
// bleeds into the neighboring hint column. Deterministic (pure string
// math over textWidth).
std::string fitLabel(const std::string& name, const std::string& suffix,
                     double scale, int availPx);

// Appends non-indexed triangle vertices for `text` (UTF-8) laid out
// from the top-left corner (x, y) in SCREEN pixels (y grows downward).
// The glyph ink is white in the atlas; the fragment shader modulates it
// by u_color, so the caller picks the text color (and alpha) at draw
// time.
void makeTextVertices(const std::string& text, int x, int y, double scale,
                      std::vector<MeshVertex>& out);

} // namespace mc
