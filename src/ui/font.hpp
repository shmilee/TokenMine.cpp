struct GlyphUv {
    float u0 = 0.0f, v0 = 0.0f, u1 = 0.0f, v1 = 0.0f; // v0 = glyph top
};

// PRE-1: decodes the next UTF-8 codepoint of `text` starting at `pos`.
// On success returns the codepoint and advances `pos` past the whole
// sequence (1..4 bytes). On malformed input (stray continuation byte,
// truncated / overlong encoding, UTF-8 surrogate, codepoint above
// U+10FFFF) returns nullopt and advances `pos` by ONE byte, so each
// malformed byte renders as its own '?'.
std::optional<uint32_t> utf8NextCodepoint(const std::string& text,
                                          std::size_t& pos);

// The 16x16 glyph rect for a decoded codepoint: ASCII 32..126 keeps the
// original cell (cp % 8, cp / 8) — bit-identical to the pre-PRE-1
// mapping; a codepoint in kCjkGlyphs takes its set position (the i-th
// sorted entry is cell (i % 8, i / 8)); everything else maps to '?'.
// (A char argument converts to its unsigned value, so a raw byte 0x80
// renders '?' exactly as before.)
GlyphUv glyphUv(uint32_t cp);

// On-screen advance width of the whole string at `scale` (> 0; values
// <= 0 clamp to 1.0): each decoded codepoint occupies kGlyphSize*scale
// plus scale pixels of spacing (CJK codepoints use the SAME 16px
// monospace advance as ASCII — the PRE-1 width discipline). Fractional
// scales downscale the glyphs.
double textWidth(const std::string& text, double scale = 1.0);

// CRAFT-4: shrink `name` (trailing codepoints) so that `name + suffix`
// fits `availPx` at `scale` — the suffix (the " xN" output count) is
// always kept, the name is truncated last-resort so a long item id never
// bleeds into the neighboring hint column. Deterministic (pure string
// math over textWidth).
std::string fitLabel(const std::string& name, const std::string& suffix,
                     double scale, int availPx);

// Appends non-indexed triangle vertices for `text` (UTF-8) laid out
// from the top-left corner (x, y) in SCREEN pixels (y grows downward).
// The glyph ink is white in the atlas; the fragment shader modulates it
// by u_color, so the caller picks the text color (and alpha) at draw
// time.
void makeTextVertices(const std::string& text, int x, int y, double scale,
                      std::vector<MeshVertex>& out);

