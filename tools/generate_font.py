def main() -> None:
    assert len(FONT) == 95, "expected ASCII 32..126"
    px = [[(0, 0, 0, 0)] * W for _ in range(H)]
    for code, glyph in FONT.items():
        assert len(glyph) == 8 and all(len(r) == 8 for r in glyph), code
        col, row = code % 8, code // 8
        for gy, line in enumerate(glyph):
            for gx, ch in enumerate(line):
                if ch == "#":
                    px[row * CELL + 4 + gy][col * CELL + 4 + gx] = (
                        255, 255, 255, 255)
    write_png(OUT, px)
    print(f"wrote {OUT} ({W}x{H}, {len(FONT)} glyphs)")


if __name__ == "__main__":
    main()
