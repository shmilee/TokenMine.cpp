"""Generate the 8x8 pixel font atlas (RGBA PNG) for Phase 15.

Deterministic: the glyph table is static data in this file, so the output
is stable across runs and platforms. Re-run after editing this file to
refresh assets/textures/font.png.

Atlas layout (128x256, 16px cells):
  - cells are indexed by ASCII code: cell (c % 8, c // 8);
  - each 8x8 glyph is drawn centered in its 16px cell (4px offset);
  - ink pixels are white with full alpha; everything else is transparent.

The game (src/ui/font.cpp) maps a character to its cell and reads the
8x8 sub-rect; unknown characters fall back to the '?' glyph.
"""
